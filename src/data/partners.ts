export const partnerById = (id: string): Partner =>
  partners.find((p) => p.id === id)!;

export const linkById = (id: string): ChainLink => links.find((l) => l.id === id)!;

export const loopById = (id: string): Loop => loops.find((l) => l.id === id)!;

export const linksForLoop = (loopId: string): ChainLink[] =>
  loops.find((l) => l.id === loopId)!.linkIds.map(linkById);

export const partnerLinks = (partnerId: string) => ({
  earns: links.filter((l) => l.fromId === partnerId),
  redeems: links.filter((l) => l.toId === partnerId),
});
